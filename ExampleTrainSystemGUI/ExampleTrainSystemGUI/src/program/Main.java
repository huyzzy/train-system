    //method to check for order's customer id foreign key violation
    public void foreignKeyViolationTicket(int passengerID) {
        if(getTicket(passengerID).getPassengerID() == -1) {
            alert("Passenger ID does not exist", "Foreign Key Violation");
        }
    }
    
    //method to check for customer primary key violation
    public void primaryKeyViolationPassenger(int passengerID) {
        if(getPassenger(passengerID).getPassengerID() != -1) {
            alert("Another passenger already exists with same Passenger ID, please try another Passenger ID", "Primary Key Violation");
        }
    }
    
    //method to check for order primary key violation
    public void primaryKeyViolationTrain(int trainID) {
        if(getTrain(trainID).getTrainID() != -1) {
            alert("Another train already exists with same Train ID, please try another Train ID", "Primary Key Violation");
        }
    }
    
    public void primaryKeyViolationSchedule(int scheduleID) {
        if(getSchedule(scheduleID).getScheduleID() != -1) {
            alert("Another schedule already exists with same schedule ID, please try another schedule ID", "Primary Key Violation");
        }
    }
    
     public void primaryKeyViolationTicket(int ticketID) {
        if(getTicket(ticketID).getTicketID() != -1) {
            alert("Another ticket already exists with same ticket ID, please try another ticket ID", "Primary Key Violation");
        }
    }
    
