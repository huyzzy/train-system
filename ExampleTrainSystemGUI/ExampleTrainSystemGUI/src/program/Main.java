    private void jButtonDeleteScheduleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteScheduleActionPerformed
       if (!jTextFieldScheduleID.getText().isEmpty()) {
            int scheduleID = Integer.parseInt(jTextFieldScheduleID.getText().trim());
            String startDateTime = jTextFieldStartDateTime.getText().trim();
            String endDateTime = jTextFieldEndDateTime.getText().trim();
            String startLocation = jTextFieldStartLocation.getText().trim();
            String destination = jTextFieldDestination.getText().trim();
            int trainID = Integer.parseInt(jTextFieldTrainID1.getText().trim());

            Schedule schedule = getSchedule(scheduleID);
            if(schedule.getScheduleID() != -1) {
                int option = JOptionPane.showConfirmDialog(rootPane, "Are you sure you want to Delete?", "Delete confirmation", JOptionPane.YES_NO_OPTION);
                if(option == 0) {
                    deleteSchedule(scheduleID, startDateTime, endDateTime, startLocation, destination, trainID);
                    refreshSchedulesTable();
                    clearScheduleTextFields();
                }
            }
            else
            {
                alert("Schedule does not exist", "Delete error");
            }
        }
        else
        {
            alert("ID cannot be empty", "Delete error");
        }
    }//GEN-LAST:event_jButtonDeleteScheduleActionPerformed

